package generator

import (
	"google.golang.org/protobuf/compiler/protogen"
)

// GenerateFile emits <prefix>.pb.plainjson.go next to the .pb.go for one proto file.
func GenerateFile(plugin *protogen.Plugin, file *protogen.File) error {
	msgs := flattenMessages(file.Messages)
	if len(msgs) == 0 {
		return nil
	}
	g := plugin.NewGeneratedFile(file.GeneratedFilenamePrefix+".pb.plainjson.go", file.GoImportPath)
	g.P("// Code generated by protoc-gen-go-plainjson. DO NOT EDIT.")
	g.P()
	g.P("package ", file.GoPackageName)
	g.P()
	for _, m := range msgs {
		_ = m
	}
	return nil
}

// flattenMessages returns every message in the file, including nested ones,
// skipping map entries (they are synthesized, not real messages).
func flattenMessages(msgs []*protogen.Message) []*protogen.Message {
	var out []*protogen.Message
	for _, m := range msgs {
		if m.Desc.IsMapEntry() {
			continue
		}
		out = append(out, m)
		out = append(out, flattenMessages(m.Messages)...)
	}
	return out
}
